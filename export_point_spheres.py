#!/usr/bin/env python3
"""
Export 3D point clouds with radii, colors, and region IDs to multiple formats
suitable for molecular viz (VMD, PyMOL, VESTA) and general particle viz (OVITO,
CloudCompare, MeshLab, ParaView).

Supported formats:
  - Extended XYZ  (OVITO, ASE, many tools)
  - PQR           (VMD, PyMOL, APBS; stores xyz + radius + charge)
  - LAMMPS dump   (OVITO natively; columns x y z radius)
  - PLY point cloud (MeshLab, CloudCompare, Blender; per-vertex color + radius)
  - PyMOL CGO script (spheres with exact RGB + radius; run inside PyMOL)

Usage:
    python export_point_spheres.py
"""

import struct
from typing import List, Tuple, Optional
import numpy as np

Point = dict  # expects keys: x, y, z, radius, color=(r,g,b), region_id, optional charge


def write_extended_xyz(
    filename: str,
    points: List[Point],
    cell: Optional[Tuple[float, float, float]] = None,
) -> None:
    """
    Extended XYZ (libAtoms / ASE spec).
    OVITO auto-maps 'radius:R:1' -> Radius and 'color:R:3' -> Color.
    VMD/PyMOL will read the coordinates but ignore extra columns.
    """
    n = len(points)
    # Default non-periodic bounding box if no cell provided
    if cell is None:
        mins = [min(p["x"] for p in points), min(p["y"] for p in points), min(p["z"] for p in points)]
        maxs = [max(p["x"] for p in points), max(p["y"] for p in points), max(p["z"] for p in points)]
        # Add padding
        padding = max(1.0, max(maxs[i] - mins[i] for i in range(3)) * 0.1)
        origin = [mins[i] - padding for i in range(3)]
        lengths = [maxs[i] - mins[i] + 2 * padding for i in range(3)]
        lattice = f"{lengths[0]} 0.0 0.0 0.0 {lengths[1]} 0.0 0.0 0.0 {lengths[2]}"
        origin_str = f' Origin="{origin[0]} {origin[1]} {origin[2]}"'
        pbc = "F F F"
    else:
        lattice = f"{cell[0]} 0.0 0.0 0.0 {cell[1]} 0.0 0.0 0.0 {cell[2]}"
        origin_str = ""
        pbc = "T T T"

    properties = 'Properties=species:S:1:pos:R:3:radius:R:1:color:R:3:region_id:I:1'
    header = f'{n}\nLattice="{lattice}" {properties} pbc="{pbc}"{origin_str}'

    lines = [header]
    for p in points:
        r, g, b = p["color"]
        lines.append(
            f"X  {p['x']:.6f}  {p['y']:.6f}  {p['z']:.6f}  "
            f"{p['radius']:.6f}  {r:.4f} {g:.4f} {b:.4f}  {p['region_id']}"
        )

    with open(filename, "w") as f:
        f.write("\n".join(lines) + "\n")


def write_pqr(filename: str, points: List[Point]) -> None:
    """
    PQR format: whitespace-delimited PDB variant storing charge and radius.
    VMD/PyMOL read the radius field natively and use it for VDW/Sphere reps.
    VESTA reads PQR via its PDB reader (may ignore radii, but will show atoms).
    """
    with open(filename, "w") as f:
        f.write("REMARK   Generated by export_point_spheres.py\n")
        for i, p in enumerate(points, start=1):
            charge = p.get("charge", 0.0)
            # Use a dummy atom name "SPH" and residue "PTS"
            line = (
                f"ATOM  {i:5d} SPH  PTS A{i:4d}    "
                f"{p['x']:8.3f} {p['y']:8.3f} {p['z']:8.3f} "
                f"{charge:7.4f} {p['radius']:7.4f}\n"
            )
            f.write(line)
        f.write("END\n")


def write_lammps_dump(filename: str, points: List[Point]) -> None:
    """
    LAMMPS custom dump with columns: id type x y z radius.
    OVITO maps 'radius' -> Radius automatically.
    Can be read by OVITO, VMD (via topotools, not natively), and other MD tools.
    """
    # Compute a loose bounding box
    xs = [p["x"] for p in points]
    ys = [p["y"] for p in points]
    zs = [p["z"] for p in points]
    pad = 1.0
    xlo, xhi = min(xs) - pad, max(xs) + pad
    ylo, yhi = min(ys) - pad, max(ys) + pad
    zlo, zhi = min(zs) - pad, max(zs) + pad

    with open(filename, "w") as f:
        f.write("ITEM: TIMESTEP\n")
        f.write("0\n")
        f.write("ITEM: NUMBER OF ATOMS\n")
        f.write(f"{len(points)}\n")
        f.write("ITEM: BOX BOUNDS pp pp pp\n")
        f.write(f"{xlo:.3f} {xhi:.3f}\n")
        f.write(f"{ylo:.3f} {yhi:.3f}\n")
        f.write(f"{zlo:.3f} {zhi:.3f}\n")
        f.write("ITEM: ATOMS id type x y z radius region_id\n")
        for i, p in enumerate(points, start=1):
            f.write(
                f"{i} 1 {p['x']:.6f} {p['y']:.6f} {p['z']:.6f} "
                f"{p['radius']:.6f} {p['region_id']}\n"
            )


def write_ply_pointcloud(filename: str, points: List[Point]) -> None:
    """
    ASCII PLY point cloud with per-vertex radius and color.
    MeshLab, CloudCompare, Blender, and general 3D tools read this natively.
    VMD/PyMOL/VESTA do NOT read PLY point clouds natively.
    """
    n = len(points)
    header_lines = [
        "ply",
        "format ascii 1.0",
        "comment point cloud with radii and colors",
        f"element vertex {n}",
        "property float x",
        "property float y",
        "property float z",
        "property float radius",
        "property uchar red",
        "property uchar green",
        "property uchar blue",
        "end_header",
    ]
    body_lines = []
    for p in points:
        r, g, b = p["color"]
        body_lines.append(
            f"{p['x']:.6f} {p['y']:.6f} {p['z']:.6f} "
            f"{p['radius']:.6f} {int(r*255)} {int(g*255)} {int(b*255)}"
        )

    with open(filename, "w") as f:
        f.write("\n".join(header_lines) + "\n")
        f.write("\n".join(body_lines) + "\n")


def write_pymol_cgo_script(filename: str, points: List[Point]) -> None:
    """
    Write a PyMOL Python script that loads spheres as a CGO object.
    Run inside PyMOL: `run script.py`
    This is the most direct way to get exact RGB + radius spheres in PyMOL.
    """
    with open(filename, "w") as f:
        f.write("from pymol.cgo import *\n")
        f.write("from pymol import cmd\n\n")
        f.write("obj = [\n")
        for p in points:
            r, g, b = p["color"]
            f.write(
                f"    COLOR, {r:.4f}, {g:.4f}, {b:.4f},\n"
                f"    SPHERE, {p['x']:.4f}, {p['y']:.4f}, {p['z']:.4f}, {p['radius']:.4f},\n"
            )
        f.write("]\n\n")
        f.write("cmd.load_cgo(obj, 'my_spheres')\n")


def demo() -> None:
    """Generate a few example points and write all formats."""
    points = [
        {"x": 0.0,  "y": 0.0,  "z": 0.0,  "radius": 1.0, "color": (1.0, 0.0, 0.0), "region_id": 1, "charge": 0.0},
        {"x": 3.0,  "y": 0.0,  "z": 0.0,  "radius": 0.5, "color": (0.0, 1.0, 0.0), "region_id": 2, "charge": 0.0},
        {"x": 0.0,  "y": 3.0,  "z": 0.0,  "radius": 1.5, "color": (0.0, 0.0, 1.0), "region_id": 1, "charge": 0.0},
        {"x": 0.0,  "y": 0.0,  "z": 3.0,  "radius": 0.8, "color": (1.0, 1.0, 0.0), "region_id": 3, "charge": 0.0},
    ]

    write_extended_xyz("points.extxyz", points)
    write_pqr("points.pqr", points)
    write_lammps_dump("points.dump", points)
    write_ply_pointcloud("points.ply", points)
    write_pymol_cgo_script("load_spheres_in_pymol.py", points)
    print("Wrote points.extxyz, points.pqr, points.dump, points.ply, load_spheres_in_pymol.py")


if __name__ == "__main__":
    demo()
